#[allow(unused_imports)]
use std::collections::BTreeMap;

/// Metadata for a single config field.
///
/// The field's dot-path is *not* stored here: it is the section prefix plus
/// `name`, composed at the one place that renders paths (the schema builder).
/// Keeping a second copy in every field would let the two drift apart.
pub struct FieldMeta {
    pub name: &'static str,
    pub ty: &'static str,
    pub default: serde_json::Value,
    pub min: Option<serde_json::Value>,
    pub max: Option<serde_json::Value>,
    pub allowed: &'static [&'static str],
    pub desc: &'static str,
    /// True when the value is a secret (e.g. api_key). Secrets are masked
    /// in the config schema and never sent back to the UI as plaintext.
    pub secret: bool,
}

/// A config struct generated by `define_config!`.
///
/// One `define_config!` declaration is the only place a field is declared; the
/// schema, the defaults, `clamp()` and the patch writer all read that one
/// declaration. Implemented by the macro, never by hand.
pub trait ScalarConfig:
    Sized + Clone + serde::Serialize + serde::de::DeserializeOwned + 'static
{
    /// Dot-path prefix of the section (e.g. `gateway.cron`).
    const SECTION: &'static str;
    /// One entry per declared field, in declaration order.
    fn field_metas() -> &'static [FieldMeta];
    /// Apply every declared constraint to the current values.
    fn clamp_fields(&mut self);
}

/// Write one scalar field of a `define_config!` struct.
///
/// The value travels through the struct's own serde form, so the field list,
/// the field's type, its JSON key and its constraints all come from the single
/// `define_config!` declaration: a newly declared scalar field is schema-visible
/// and writable with no other edit. Unknown field names and collection-typed
/// fields are rejected instead of being written as unknown JSON.
pub fn set_scalar<T: ScalarConfig>(
    target: &mut T,
    section: &str,
    field: &str,
    value: &serde_json::Value,
) -> Result<(), String> {
    let meta = T::field_metas()
        .iter()
        .find(|m| m.name.trim_start_matches("r#") == field)
        .ok_or_else(|| format!("Unknown {} field: {}", section, field))?;
    if is_collection_section(meta) {
        return Err(format!(
            "{}.{}: edited as its own collection, not as a scalar field",
            section, field
        ));
    }
    let path = format!("{}.{}", section, field);
    check_shape(meta, value, &path)?;
    let mut object = match serde_json::to_value(&*target) {
        Ok(serde_json::Value::Object(map)) => map,
        Ok(_) => return Err(format!("{}: section is not a JSON object", section)),
        Err(e) => return Err(format!("{}: cannot read section: {}", section, e)),
    };
    object.insert(field.to_string(), value.clone());
    let mut next: T = serde_json::from_value(serde_json::Value::Object(object))
        .map_err(|e| format!("{}: invalid value: {}", path, e))?;
    next.clamp_fields();
    *target = next;
    Ok(())
}

/// True for a field whose items have their own editor section (backends,
/// secrets, MCP servers). Those are written through add/remove plus per-item
/// paths; a plain `set` on the whole array is not a scalar write.
///
/// `Vec<String>` is the exception: it is a leaf list with no per-item section
/// (MCP `args`), so it stays writable as one value.
fn is_collection_section(meta: &FieldMeta) -> bool {
    meta.ty.starts_with("Vec<") && meta.ty != "Vec<String>"
}

/// Shape check for the one field family serde describes badly: a masked
/// string table (`BTreeMap<String, String>`, e.g. an MCP server's `env`).
/// serde reports those as `expected a map`, which loses the field's meaning
/// for the editor; the editor's contract is a JSON object of strings.
fn check_shape(meta: &FieldMeta, value: &serde_json::Value, path: &str) -> Result<(), String> {
    if !meta.ty.starts_with("BTreeMap<") {
        return Ok(());
    }
    let object = value
        .as_object()
        .ok_or_else(|| format!("{}: expected a JSON object of strings", path))?;
    for (key, entry) in object {
        if !entry.is_string() {
            return Err(format!("{}.{}: expected a string", path, key));
        }
    }
    Ok(())
}

/// Define config structs with embedded metadata.
///
/// `$section` is the section's dot-path prefix (e.g. `"gateway.cron"`). It is
/// the single source for the schema section name and for every field path
/// under it (`gateway.cron.enabled`), so no prefix is written twice.
///
/// One declaration yields the struct, its `Default`, its `FieldMeta` list, its
/// `clamp()`, and its [`ScalarConfig`] impl — which is what makes a new scalar
/// field schema-visible and patch-writable with no other edit.
///
/// Constraint helpers:
/// - `range(min, max)` — numeric range clamp
/// - `str_max(n)` — String max length (truncation)
/// - `allowed(["val1", "val2"])` — whitelist (fallback to default)
/// - `allowed_max(["val1", "val2"], n)` — whitelist + max length
/// - `secret` — no clamp, but marks the field as a secret (masked in schema)
/// - `none` — no constraint
#[macro_export]
macro_rules! define_config {
    (
        $section:literal => $name:ident {
            $(
                $field:ident : $fty:ty = $def:expr,
                $cname:tt $( ($($args:tt)+) )? ,
                desc: $desc:expr,
            )+
        }
    ) => {
        $crate::_cfg_mixed_expand!(
            @sec $section, $name,
            [ $( ($field, $fty, $def, $cname $( ($($args)+) )? , $desc) )+ ]
        );
    };
}

// ── Mixed-constraint expander ──

#[doc(hidden)]
#[macro_export]
macro_rules! _cfg_mixed_expand {
    (@sec $section:literal, $name:ident,
     [ $( ($field:ident, $fty:ty, $def:expr, $cname:tt $( ($($args:tt)+) )? , $desc:expr) )+ ]) => {
        #[derive(Clone, Debug, serde::Serialize, serde::Deserialize, PartialEq)]
        #[serde(default)]
        pub struct $name {
            $( pub $field: $fty, )+
            #[serde(flatten)]
            pub unknown: serde_json::Map<String, serde_json::Value>,
        }
        impl Default for $name {
            fn default() -> Self {
                Self { $( $field: $def, )+ unknown: Default::default() }
            }
        }
        impl $crate::config_macro::ScalarConfig for $name {
            const SECTION: &'static str = $section;
            fn field_metas() -> &'static [$crate::config_macro::FieldMeta] {
                Self::fields()
            }
            fn clamp_fields(&mut self) {
                self.clamp()
            }
        }
        impl $name {
            pub fn fields() -> &'static [$crate::config_macro::FieldMeta] {
                Box::leak(Box::new([
                    $( $crate::_cfg_field_meta!(
                        $field, $fty, $def, $cname $( ($($args)+) )? , $desc
                    ) ),+
                ]))
            }
            pub fn defaults() -> &'static BTreeMap<&'static str, serde_json::Value> {
                use std::sync::OnceLock;
                static CACHE: OnceLock<BTreeMap<&'static str, serde_json::Value>> = OnceLock::new();
                CACHE.get_or_init(|| BTreeMap::from_iter([$( (stringify!($field), serde_json::json!($def)), )+]))
            }
            pub fn clamp(&mut self) {
                #[allow(unused_variables)]
                let s = &mut *self;
                $(
                    $crate::_clamp_gen!(s.$field, $fty, $def, $cname $( ($($args)+) )?);
                )+
            }
        }
    };
}

// ── Clamp code generation ──
// Uses $self:expr to access struct fields via the local `s` binding.

#[doc(hidden)]
#[macro_export]
macro_rules! _clamp_gen {
    // range: numeric clamp
    ($self:expr, $fty:ty, $def:expr, range($min:tt, $max:tt)) => {
        $self = $self.clamp($min as _, $max as _);
    };
    // str_max: String truncate
    ($self:expr, $fty:ty, $def:expr, str_max($max:tt)) => {
        if !$self.is_empty() {
            let max_len = $max as usize;
            if $self.len() > max_len { $self.truncate(max_len); }
        }
    };
    // allowed: String whitelist fallback
    ($self:expr, $fty:ty, $def:expr, allowed([$($v:tt),+])) => {
        if !$self.is_empty() && ![$($v),+].contains(&$self.as_str()) {
            $self = $def.into();
        }
    };
    // allowed_max: String whitelist + max length
    ($self:expr, $fty:ty, $def:expr, allowed_max([$($v:tt),+], $mx:tt)) => {
        if !$self.is_empty() {
            let max_len = $mx as usize;
            if $self.len() > max_len { $self.truncate(max_len); }
            if ![$($v),+].contains(&$self.as_str()) {
                $self = $def.into();
            }
        }
    };
    // none: no constraint
    ($self:expr, $fty:ty, $def:expr, none) => {};
    // secret: no constraint (masked in schema, value passthrough)
    ($self:expr, $fty:ty, $def:expr, secret) => {};
}

// ── FieldMeta generator ──

#[doc(hidden)]
#[macro_export]
macro_rules! _cfg_field_meta {
    ($field:ident, $fty:ty, $def:expr, $c:tt($($a:tt)+), $desc:expr) => {
        $crate::_cfg_field_meta!(@dispatch $c, $field, $fty, $def, $($a)+, $desc)
    };
    ($field:ident, $fty:ty, $def:expr, none, $desc:expr) => {
        $crate::config_macro::FieldMeta {
            name: stringify!($field),
            ty: stringify!($fty),
            default: serde_json::json!($def),
            min: None, max: None, allowed: &[], desc: $desc, secret: false,
        }
    };
    ($field:ident, $fty:ty, $def:expr, secret, $desc:expr) => {
        $crate::config_macro::FieldMeta {
            name: stringify!($field),
            ty: stringify!($fty),
            default: serde_json::json!($def),
            min: None, max: None, allowed: &[], desc: $desc, secret: true,
        }
    };

    // allowed_max must be matched before the generic two-argument arm below
    // (both take two token groups, but only allowed_max carries a whitelist).
    (@dispatch allowed_max, $field:ident, $fty:ty, $def:expr, [$($v:tt),+], $mx:tt, $desc:expr) => {
        $crate::config_macro::FieldMeta {
            name: stringify!($field),
            ty: stringify!($fty),
            default: serde_json::json!($def),
            min: None, max: Some(serde_json::json!($mx)), allowed: &[$($v),+], desc: $desc, secret: false,
        }
    };
    (@dispatch $kind:tt, $field:ident, $fty:ty, $def:expr, $min:tt, $max:tt, $desc:expr) => {
        $crate::config_macro::FieldMeta {
            name: stringify!($field),
            ty: stringify!($fty),
            default: serde_json::json!($def),
            min: Some(serde_json::json!($min)),
            max: Some(serde_json::json!($max)), allowed: &[], desc: $desc, secret: false,
        }
    };
    (@dispatch $kind:tt, $field:ident, $fty:ty, $def:expr, $max:tt, $desc:expr) => {
        $crate::_cfg_field_meta!(@str_dispatch $kind, $field, $fty, $def, $max, $desc)
    };

    (@str_dispatch str_max, $field:ident, $fty:ty, $def:expr, $max:tt, $desc:expr) => {
        $crate::config_macro::FieldMeta {
            name: stringify!($field),
            ty: stringify!($fty),
            default: serde_json::json!($def),
            min: None, max: Some(serde_json::json!($max)), allowed: &[], desc: $desc, secret: false,
        }
    };
    (@str_dispatch allowed, $field:ident, $fty:ty, $def:expr, [$($v:tt),+], $desc:expr) => {
        $crate::config_macro::FieldMeta {
            name: stringify!($field),
            ty: stringify!($fty),
            default: serde_json::json!($def),
            min: None, max: None, allowed: &[$($v),+], desc: $desc, secret: false,
        }
    };
}

// ── Tests ──

#[cfg(test)]
mod tests {
    use super::*;

    define_config! {
        "test" => TestConfig {
            count: u32 = 10, range(1, 100), desc: "Test count",
            ratio: f32 = 0.5, range(0.0, 1.0), desc: "Test ratio",
            name: String = "default".to_string(), str_max(32), desc: "Test name",
            enabled: bool = true, none, desc: "Test enabled",
            kind: String = "a".to_string(), allowed(["a", "b", "c"]), desc: "Test kind",
            secret_key: String = "".to_string(), secret, desc: "Test secret key",
            region: String = "us".to_string(), allowed_max(["us", "eu"], 4), desc: "Test region",
        }
    }

    #[test]
    fn test_struct_has_all_fields() {
        let c = TestConfig::default();
        assert_eq!(c.count, 10);
        assert!((c.ratio - 0.5).abs() < f32::EPSILON);
        assert_eq!(c.name, "default");
        assert!(c.enabled);
        assert_eq!(c.kind, "a");
    }

    #[test]
    fn test_schema_has_all_metas() {
        let metas = TestConfig::fields();
        assert_eq!(metas.len(), 7);
        let count_meta = metas.iter().find(|m| m.name == "count").unwrap();
        // The section lives on the type, the field name on the meta: the
        // dot-path is composed where paths are rendered, never stored twice.
        assert_eq!(TestConfig::SECTION, "test");
        assert_eq!(count_meta.ty, "u32");
        assert_eq!(count_meta.desc, "Test count");
    }

    #[test]
    fn test_secret_field_meta() {
        let metas = TestConfig::fields();
        // Only the `secret` constraint marks a field as secret.
        let key_meta = metas.iter().find(|m| m.name == "secret_key").unwrap();
        assert!(key_meta.secret);
        assert_eq!(key_meta.name, "secret_key");
        for m in metas.iter().filter(|m| m.name != "secret_key") {
            assert!(!m.secret, "field {} must not be secret", m.name);
        }
    }

    #[test]
    fn test_allowed_max_meta_has_whitelist_and_max() {
        let metas = TestConfig::fields();
        let region_meta = metas.iter().find(|m| m.name == "region").unwrap();
        assert_eq!(region_meta.allowed, &["us", "eu"]);
        assert_eq!(region_meta.max, Some(serde_json::json!(4)));
        assert_eq!(region_meta.min, None);
    }

    #[test]
    fn test_clamp_allowed_max_fallback() {
        let mut c = TestConfig {
            count: 10,
            ratio: 0.5,
            name: "ok".to_string(),
            enabled: true,
            kind: "a".to_string(),
            secret_key: "sk-123".to_string(),
            region: "xx".to_string(),
            unknown: Default::default(),
        };
        c.clamp();
        // secret passes through untouched; invalid allowed_max value falls back.
        assert_eq!(c.secret_key, "sk-123");
        assert_eq!(c.region, "us");
    }

    #[test]
    fn test_defaults_returns_all() {
        let defaults = TestConfig::defaults();
        assert!(defaults.contains_key("count"));
        assert!(defaults.contains_key("ratio"));
        assert!(defaults.contains_key("name"));
        assert!(defaults.contains_key("enabled"));
        assert!(defaults.contains_key("kind"));
        assert!(defaults.contains_key("secret_key"));
        assert!(defaults.contains_key("region"));
        assert_eq!(defaults["count"], serde_json::json!(10));
        assert_eq!(defaults["secret_key"], serde_json::json!(""));
    }

    #[test]
    fn test_clamp_numeric() {
        let mut c = TestConfig {
            count: 999,
            ratio: 5.0,
            name: "ok".to_string(),
            enabled: true,
            kind: "a".to_string(),
            secret_key: "".to_string(),
            region: "us".to_string(),
            unknown: Default::default(),
        };
        c.clamp();
        assert_eq!(c.count, 100);
        assert!((c.ratio - 1.0).abs() < f32::EPSILON);
    }

    #[test]
    fn test_clamp_string_allowed_fallback() {
        let mut c = TestConfig {
            count: 10,
            ratio: 0.5,
            name: "ok".to_string(),
            enabled: true,
            kind: "invalid".to_string(),
            secret_key: "".to_string(),
            region: "us".to_string(),
            unknown: Default::default(),
        };
        c.clamp();
        assert_eq!(c.kind, "a");
    }

    #[test]
    fn test_clamp_string_max_truncate() {
        let mut c = TestConfig {
            count: 10,
            ratio: 0.5,
            name: "this is a very long name that exceeds 32 chars".to_string(),
            enabled: true,
            kind: "a".to_string(),
            secret_key: "".to_string(),
            region: "us".to_string(),
            unknown: Default::default(),
        };
        c.clamp();
        assert!(c.name.len() <= 32);
    }

    #[test]
    fn test_unknown_fields_roundtrip() {
        let json = r#"{
            "count": 10,
            "ratio": 0.5,
            "name": "test",
            "enabled": true,
            "kind": "a",
            "secret_key": "",
            "region": "us",
            "future_field": "hello",
            "another": 42
        }"#;
        let c: TestConfig = serde_json::from_str(json).unwrap();
        assert!(c.unknown.contains_key("future_field"));
        assert!(c.unknown.contains_key("another"));
        let out = serde_json::to_string(&c).unwrap();
        assert!(out.contains("future_field"));
    }
}
